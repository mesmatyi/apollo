def canonical_label(label, pkg):
    """Returns `//pkg:name` / `@repo//pkg:name` for any Bazel label form."""
    label = label.strip()
    if label.startswith('@//'):
        label = label[1:]
    if label.startswith('@'):
        if '//' not in label:
            repo = label[1:]
            return '@%s//:%s' % (repo, repo)
        repo, rest = label[1:].split('//', 1)
        if ':' not in rest:
            rest = '%s:%s' % (rest, rest.split('/')[-1] if rest else repo)
        return '@%s//%s' % (repo, rest)
    if label.startswith('//'):
        rest = label[2:]
        if ':' not in rest:
            rest = '%s:%s' % (rest, rest.split('/')[-1])
        return '//' + rest
    if label.startswith(':'):
        return '//%s%s' % (pkg, label)
    return '//%s:%s' % (pkg, label)


def split_label(label):
    pkg, name = label[2:].split(':', 1)
    return pkg, name


