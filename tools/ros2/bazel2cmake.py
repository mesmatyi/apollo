# Configurable values (select)
###############################################################################
class CList(object):
    """A list whose parts may be select() dictionaries."""

    def __init__(self, parts):
        self.parts = parts  # each part: ('list', [...]) or ('select', {k: [...]})

    @staticmethod
    def of(value):
        if value is None:
            return CList([])
        if isinstance(value, CList):
            return value
        if isinstance(value, (list, tuple)):
            return CList([('list', list(value))])
        if isinstance(value, str):
            return CList([('list', [value])])
        raise GenError('unsupported list value %r' % (value,))

    def __add__(self, other):
        return CList(self.parts + CList.of(other).parts)

    def __radd__(self, other):
        return CList(CList.of(other).parts + self.parts)

    def __iter__(self):
        # Only reached when a BUILD file iterates a select(); use the
        # unconditional entries plus the default branch.
        for value, conds in self.entries():
            if not conds or all(c.startswith('!') for c in conds):
                yield value

    def __len__(self):
        return len(list(iter(self)))

    def entries(self):
        """Returns [(value, (cond, ...))] where conds is a tuple of strings."""
        out = []
        for kind, data in self.parts:
            if kind == 'list':
                out.extend((v, ()) for v in data)
                continue
            keys = [k for k in data if k != DEFAULT_CONDITION]
            names = [CONDITIONS.get(k, _cond_name(k)) for k in keys]
            for key, name in zip(keys, names):
                for v in CList.of(data[key]).entries():
                    out.append((v[0], tuple(v[1]) + (name,)))
            if DEFAULT_CONDITION in data:
                neg = tuple('!' + n for n in sorted(set(names)))
                for v in CList.of(data[DEFAULT_CONDITION]).entries():
                    out.append((v[0], tuple(v[1]) + neg))
        return out


def _cond_name(key):
    return re.sub(r'[^A-Za-z0-9_]', '_', key.split(':')[-1])


def select(branches, no_match_error=None):
    return CList([('select', dict(branches))])


def _entries(value):
    return CList.of(value).entries()


def _shell_tokens(entries):
    out = []
    for v, conds in entries:
        try:
            toks = shlex.split(v)
        except ValueError:
            toks = [v]
        out.extend((t, conds) for t in toks)
    return out


