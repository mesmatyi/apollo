"""Converts the Bazel BUILD files under modules/ into declarative CMake.

The BUILD files stay the source of truth.  Each one is evaluated as
Python/Starlark with stub implementations of load(), glob(), select(),
package() and of the Apollo macros (apollo_cc_library, apollo_component,
apollo_plugin, proto_library, ...).  The stubs only *record* target specs;
nothing is built here.

Outputs (all deterministic, re-run after editing any BUILD/.proto file):

  modules/<bazel package>/BUILD.cmake
      One per BUILD file that declares something.  It only contains
      `apollo_bazel_package()` / `apollo_target()` calls, i.e. declarations
      (kind, name, srcs, hdrs, deps, copts, ...).  Labels are canonical
      (`//pkg:name`, `@repo//pkg:name`); select() branches become
      `cond1,!cond2?value` entries that CMake filters.
  modules/cmake/generated/apollo_packages.cmake
      The list of BUILD.cmake files to include.
  modules/cmake/generated/apollo_protos.cmake
      Every .proto file under modules/ with its imports and the protobuf
      library it is compiled into (see "proto partitioning" below).

The top-level modules/CMakeLists.txt reads all declarations first and only
then resolves labels, maps external repositories to find_package() results
and transitively skips targets whose dependencies are unavailable.

Proto partitioning: all protos go into one library `apollo_proto`, except
files that define a fully-qualified symbol that another file also defines
(e.g. the per-vehicle canbus protos vs. chassis_detail.proto).  Linking two
such files into one process aborts in protobuf's generated pool, so each of
them -- and, transitively, every file importing one -- gets its own library.

Usage:
  tools/ros2/bazel2cmake.py            # regenerate
  tools/ros2/bazel2cmake.py --check    # exit 1 if outputs are stale
"""

