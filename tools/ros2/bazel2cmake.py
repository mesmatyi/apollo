class Evaluator(object):
    def __init__(self, root, globber):
        self.root = root
        self.globber = globber
        self.pkg = None
        self.warnings = []

    # -- helpers -------------------------------------------------------------
    def warn(self, msg):
        self.warnings.append('%s: %s' % (self.pkg.path, msg))

    def _target(self, kind, name, extra_names=(), weak_names=(), **kw):
        t = Target(kind, self.pkg.path, name)
        for field in Target.FIELDS:
            if field in kw and kw[field] is not None:
                t.add(field, kw[field])
        return self.pkg.add(t, extra_names, weak_names)

    @staticmethod
    def _split_copts(copts):
        """-D copts become local defines (CMake escapes them properly).

        Like Bazel, copts are Bourne-shell tokenized first, so that
        '-DMODULE_NAME=\\"control\\"' becomes MODULE_NAME="control"."""
        defines, rest = [], []
        for v, conds in _shell_tokens(_entries(copts)):
            if v.startswith('-D') and len(v) > 2:
                defines.append((v[2:], conds))
            else:
                rest.append((v, conds))
        return defines, rest

    def _cc(self, kind, name, extra_names=(), srcs=None, hdrs=None, deps=None,
            copts=None, defines=None, local_defines=None, linkopts=None,
            includes=None, data=None, textual_hdrs=None,
            strip_include_prefix=None, include_prefix=None, **_ignored):
        t = self._target(kind, name, extra_names, srcs=srcs, hdrs=hdrs,
                         deps=deps, includes=includes, data=data)
        for field, value in (('defines', defines), ('local_defines', local_defines),
                             ('linkopts', linkopts)):
            t.values[field].extend(_shell_tokens(_entries(value)))
        if textual_hdrs:
            t.add('hdrs', textual_hdrs)
        cdefs, rest = self._split_copts(copts)
        t.values['local_defines'].extend(cdefs)
        t.values['copts'].extend(rest)
        if strip_include_prefix:
            t.values['includes'].append((strip_include_prefix.lstrip('/'), ()))
        if include_prefix:
            self.warn('%s: include_prefix is not supported' % name)
        return t

    # -- generic Bazel ---------------------------------------------------------
    def load(self, *args, **kwargs):
        pass  # symbols are pre-bound in the evaluation namespace

    def package(self, **kwargs):
        pass

    def glob(self, include, exclude=(), exclude_directories=1, allow_empty=True):
        return self.globber.glob(self.pkg.path, include, exclude, exclude_directories)

    def package_name(self):
        return self.pkg.path

    def repository_name(self):
        return '@'

    def noop(self, *args, **kwargs):
        pass

    def fail(self, msg='', *args):
        raise GenError('%s: fail(): %s' % (self.pkg.path, msg))

    # -- C++ rules -------------------------------------------------------------
    def cc_library(self, name, alwayslink=False, linkstatic=False, **kw):
        if any(v.endswith(('.so', '.a')) and not v.startswith(':')
               for v, _ in _entries(kw.get('srcs'))):
            self.warn('%s: prebuilt library srcs' % name)
        return self._cc('cc_library', name, **kw)

    def apollo_cc_library(self, name, **kw):
        kw.pop('alwayslink', None)
        return self._cc('cc_library', name, ['lib%s.so' % name], **kw)

    def cc_binary(self, name, linkshared=False, linkstatic=False, **kw):
        if linkshared or name.endswith('.so'):
            t = self._cc('cc_shared', name, **kw)
            t.output_name = name
            return t
        return self._cc('cc_binary', name, **kw)

    def apollo_cc_binary(self, name, **kw):
        kw.pop('auto_find_deps', None)
        return self.cc_binary(name, **kw)

    def cc_test(self, name, size=None, timeout=None, flaky=None, shard_count=None,
                tags=None, args=None, local=None, linkstatic=None, **kw):
        t = self._cc('cc_test', name, **kw)
        return t

    def apollo_cc_test(self, name, **kw):
        kw.pop('auto_find_deps', None)
        return self.cc_test(name, **kw)

    def apollo_component(self, name, **kw):
        if not (name.startswith('lib') and name.endswith('.so')):
            raise GenError('%s: apollo_component name must be lib*.so' % name)
        base = name[3:-3]
        kw.pop('alwayslink', None)
        t = self._cc('component', name, ['DO_NOT_IMPORT_' + base], **kw)
        t.output_name = name
        return t

    def apollo_plugin(self, name, description=None, **kw):
        if not (name.startswith('lib') and name.endswith('.so')):
            raise GenError('%s: apollo_plugin name must be lib*.so' % name)
        base = name[3:-3]
        kw.pop('alwayslink', None)
        t = self._cc('plugin', name, ['%s_lib' % base], **kw)
        t.output_name = name
        t.plugin_description = canonical_label(description, self.pkg.path)
        return t

    def cyber_plugin_description(self, name, description, plugin):
        self.pkg.plugin_descriptions[canonical_label(plugin, self.pkg.path)] = \
            canonical_label(description, self.pkg.path)

    def gpu_library(self, name, mandatory=True, copts=None, **kw):
        t = self.apollo_cc_library(name, copts=copts, **kw) if mandatory else \
            self.cc_library(name, copts=copts, **kw)
        return t

    def cuda_library(self, name, **kw):
        return self.gpu_library(name, **kw)

    def apollo_qt_library(self, name, srcs=None, hdrs=None, uis=(), res=(),
                          normal_hdrs=(), data=None, deps=None, copts=None, **kw):
        t = self._cc('qt_library', name, srcs=srcs, hdrs=list(hdrs or []) + list(normal_hdrs),
                     deps=deps, copts=copts)
        t.add('data', list(uis) + list(res))
        return t

    def cc_grpc_library(self, name, srcs=None, deps=None, grpc_only=False, **kw):
        t = self._target('cc_library', name, deps=deps)
        t.add('deps', ['@com_github_grpc_grpc//:grpc++'])
        for v, conds in _entries(srcs):
            t.values['deps'].append((v, conds))
        return t

    # -- protos ----------------------------------------------------------------
    def proto_library(self, name, srcs=None, deps=None, tags=None, **kw):
        names = []
        if name.endswith('proto'):
            stem = name[:-len('proto')]
            names = [stem + 'cc_proto', stem + 'py_pb2', '%s_py_pb2' % name,
                     '_%s' % name, '_%s_cc_proto' % name, '_%s_cc_lib' % name]
        names = [n for n in names if n != name]
        return self._target('proto', name, weak_names=names, srcs=srcs, deps=deps)

    def cc_proto_library(self, name, deps=None, **kw):
        return self._target('proto', name, deps=deps)

    def py_proto_library(self, name, deps=None, srcs=None, **kw):
        return self._target('proto', name, deps=deps, srcs=srcs)

    # -- data / python -----------------------------------------------------------
    def filegroup(self, name, srcs=None, data=None, **kw):
        t = self._target('filegroup', name, srcs=srcs)
        if data:
            t.add('srcs', data)
        return t

    def py_library(self, name, srcs=None, deps=None, data=None, **kw):
        return self._target('py_library', name, srcs=srcs, deps=deps, data=data)

    def py_binary(self, name, srcs=None, deps=None, data=None, main=None, **kw):
        t = self._target('py_binary', name, srcs=srcs, deps=deps, data=data)
        if main:
            t.flags.append('MAIN=' + main)
        return t

    def py_test(self, name, srcs=None, deps=None, data=None, **kw):
        return self._target('py_test', name, srcs=srcs, deps=deps, data=data)

    # -- evaluation ------------------------------------------------------------
    def namespace(self):
        ns = {
            '__builtins__': __builtins__,
            'load': self.load, 'package': self.package, 'glob': self.glob,
            'select': select, 'package_name': self.package_name,
            'repository_name': self.repository_name, 'fail': self.fail,
            'licenses': self.noop, 'exports_files': self.noop,
            'cpplint': self.noop, 'apollo_package': self.noop,
            'install': self.noop, 'install_files': self.noop,
            'install_src_files': self.noop, 'install_plugin': self.noop,
            'cc_library': self.cc_library, 'cc_binary': self.cc_binary,
            'cc_test': self.cc_test,
            'apollo_cc_library': self.apollo_cc_library,
            'apollo_cc_binary': self.apollo_cc_binary,
            'apollo_cc_test': self.apollo_cc_test,
            'apollo_component': self.apollo_component,
            'apollo_plugin': self.apollo_plugin,
            'apollo_qt_library': self.apollo_qt_library,
            'cyber_plugin_description': self.cyber_plugin_description,
            'gpu_library': self.gpu_library, 'cuda_library': self.cuda_library,
            'cc_grpc_library': self.cc_grpc_library,
            'proto_library': self.proto_library,
            'cc_proto_library': self.cc_proto_library,
            'py_proto_library': self.py_proto_library,
            'filegroup': self.filegroup,
            'py_library': self.py_library, 'py_binary': self.py_binary,
            'py_test': self.py_test,
            'apollo_py_library': self.py_library,
            'apollo_py_binary': self.py_binary,
            # tools/platform/build_defs.bzl and third_party/gpus/common.bzl
            'if_gpu': lambda t, f=[]: select({'//tools/platform:use_gpu': t, DEFAULT_CONDITION: f}),
            'copts_if_gpu': lambda: select({'//tools/platform:use_gpu': ['-DUSE_GPU=1'],
                                            DEFAULT_CONDITION: ['-DUSE_GPU=0']}),
            'if_cuda': lambda t, f=[]: select({'@local_config_cuda//cuda:using_nvcc': t,
                                                DEFAULT_CONDITION: f}),
            'if_rocm': lambda t, f=[]: select({'@local_config_rocm//rocm:using_hipcc': t,
                                                DEFAULT_CONDITION: f}),
            'if_teleop': lambda t, f=[]: select({'//tools/platform:with_teleop': t,
                                                  DEFAULT_CONDITION: f}),
            'copts_if_teleop': lambda: select({'//tools/platform:with_teleop': ['-DWITH_TELEOP=1'],
                                               DEFAULT_CONDITION: ['-DWITH_TELEOP=0']}),
            'if_x86_64': lambda t, f=[]: select({'@platforms//cpu:x86_64': t, DEFAULT_CONDITION: f}),
            'if_aarch64': lambda t, f=[]: select({'@platforms//cpu:aarch64': t,
                                                   DEFAULT_CONDITION: f}),
            'if_esd_can': lambda t, f=[]: select({'//tools/platform:use_esd_can': t,
                                                   DEFAULT_CONDITION: f}),
            'copts_if_esd_can': lambda: select({'//tools/platform:use_esd_can': ['-DUSE_ESD_CAN=1'],
                                                DEFAULT_CONDITION: ['-DUSE_ESD_CAN=0']}),
            'if_profiler': lambda: select({'//tools/platform:enable_profiler': ['-DENABLE_PROFILER=1'],
                                           DEFAULT_CONDITION: ['-DENABLE_PROFILER=0']}),
        }

        class Native(object):
            pass
        native = Native()
        for k, v in ns.items():
            if callable(v):
                setattr(native, k, v)
        native.existing_rules = lambda: {}
        ns['native'] = native
        return ns

    def evaluate(self, pkg_path):
        self.pkg = Package(pkg_path)
        build = os.path.join(self.root, pkg_path, 'BUILD')
        with open(build, encoding='utf-8') as f:
            code = f.read()
        try:
            exec(compile(code, build, 'exec'), self.namespace())
        except GenError:
            raise
        except Exception as e:  # pylint: disable=broad-except
            raise GenError('%s: %s: %s' % (build, type(e).__name__, e))
        return self.pkg


