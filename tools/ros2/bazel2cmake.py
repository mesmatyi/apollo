# Resolution of cross-package references / component classes
###############################################################################
class Model(object):
    def __init__(self, root):
        self.root = root
        self.packages = {}
        self.labels = {}
        self.warnings = []

    def add_package(self, pkg):
        self.packages[pkg.path] = pkg
        for t in pkg.targets:
            for n in [t.name] + t.aliases:
                self.labels['//%s:%s' % (pkg.path, n)] = t

    def file_exists(self, path):
        return os.path.isfile(os.path.join(self.root, path))

    def resolve_files(self, t, field):
        """Turns srcs/hdrs/data entries into package-relative paths or
        `//pkg:file` references; target labels in srcs move to deps."""
        out = []
        for v, conds in t.values[field]:
            if v.startswith(('//', ':', '@')):
                label = canonical_label(v, t.pkg)
                if label.startswith('@'):
                    if field == 'srcs':
                        t.values['deps'].append((label, conds))
                    continue
                pkg, name = split_label(label)
                target = self.labels.get(label)
                if target is not None and target.kind == 'filegroup':
                    for fv, fconds in self.resolve_files(target, 'srcs'):
                        path = fv[2:].replace(':', '/') if fv.startswith('//') else \
                            '%s/%s' % (target.pkg, fv)
                        out.append((self._rel(t.pkg, path), conds + fconds))
                    continue
                if target is not None:
                    if field == 'srcs' and target.kind != 'filegroup':
                        t.values['deps'].append((label, conds))
                    continue
                path = '%s/%s' % (pkg, name)
                out.append((self._rel(t.pkg, path), conds))
            else:
                out.append((v, conds))
        return out

    @staticmethod
    def _rel(pkg, path):
        if path.startswith(pkg + '/'):
            return path[len(pkg) + 1:]
        pkg_of, _, name = path.rpartition('/')
        return '//%s:%s' % (pkg_of, name)

    def finalize(self, proto_lib):
        used_names = {}
        for path in sorted(self.packages):
            pkg = self.packages[path]
            regs = None
            for t in pkg.targets:
                t.values['srcs'] = self.resolve_files(t, 'srcs')
                t.values['hdrs'] = self.resolve_files(t, 'hdrs')
                if t.kind in ('filegroup', 'py_library', 'py_binary', 'py_test', 'qt_library'):
                    t.values['data'] = self.resolve_files(t, 'data')
                else:
                    t.values['data'] = []
                deps = []
                for v, conds in t.values['deps']:
                    deps.append((canonical_label(v, t.pkg), conds))
                t.values['deps'] = _dedupe(deps)
                optional = OPTIONAL_DEPS.get(t.label, {})
                if optional:
                    t.optional_deps = [(d, optional[d]) for d, c in t.values['deps']
                                       if d in optional]
                    t.values['deps'] = [(d, c) for d, c in t.values['deps']
                                        if d not in optional]
                for field in ('srcs', 'hdrs', 'data', 'copts', 'linkopts',
                              'defines', 'local_defines', 'includes'):
                    t.values[field] = _dedupe(t.values[field])
                # missing files / GPU sources
                for field in ('srcs', 'hdrs'):
                    for v, conds in t.values[field]:
                        p = v[2:].replace(':', '/') if v.startswith('//') else '%s/%s' % (t.pkg, v)
                        if t.kind != 'proto' and not conds and not self.file_exists(p):
                            t.broken.append('missing source file %s' % p)
                        if not conds and (v.endswith(GPU_SRC_EXT) or (
                                v.endswith(CC_SRC_EXT + ('.h', '.hpp')) and
                                uses_cuda_api(os.path.join(self.root, p)))):
                            # .cu sources, or C++ sources calling the CUDA API
                            # without a USE_GPU guard (the BUILD file does not
                            # declare the CUDA dependency): needs CUDA.
                            if (CUDA_REQUIREMENT, ()) not in t.values['deps']:
                                t.values['deps'].append((CUDA_REQUIREMENT, ()))
                        if not conds and v.endswith(CC_SRC_EXT + ('.h', '.hpp')):
                            for sdk in undeclared_sdks(os.path.join(self.root, p)):
                                if (sdk, ()) not in t.values['deps']:
                                    t.values['deps'].append((sdk, ()))
                if t.kind == 'proto':
                    for v, conds in t.values['srcs']:
                        p = v[2:].replace(':', '/') if v.startswith('//') else '%s/%s' % (t.pkg, v)
                        if p not in proto_lib:
                            t.broken.append('missing proto file %s' % p)
                if t.kind == 'plugin' and t.plugin_description:
                    dpkg, dname = split_label(t.plugin_description)
                    if not self.file_exists(os.path.join(dpkg, dname)):
                        t.broken.append('missing plugin description %s/%s' % (dpkg, dname))
            # plugin descriptions declared with cyber_plugin_description()
            for plugin_label, desc in sorted(pkg.plugin_descriptions.items()):
                t = self.labels.get(plugin_label)
                if t is None:
                    self.warnings.append('%s: cyber_plugin_description for unknown %s'
                                         % (path, plugin_label))
                    continue
                if t.kind == 'cc_shared':
                    t.kind = 'plugin'
                t.plugin_description = desc
            # component classes
            if any(t.kind in ('component', 'cc_shared', 'plugin', 'cc_library') for t in pkg.targets):
                regs = find_registered_components(os.path.join(self.root, path))
            for cls, fq, fpath in regs or []:
                rel = os.path.relpath(fpath, os.path.join(self.root, path))
                owners = [t for t in pkg.targets
                          if t.kind in ('component', 'cc_shared', 'plugin', 'cc_library')
                          and any(v == rel for v, _ in t.values['srcs'] + t.values['hdrs'])]
                loadable = [t for t in owners if t.kind in ('component', 'cc_shared')]
                if not loadable:
                    libs = {o.label for o in owners}
                    loadable = [t for t in pkg.targets if t.kind in ('component', 'cc_shared')
                                and any(d in libs for d, _ in t.values['deps'])]
                if not loadable:
                    # An apollo_cc_library holding a component: Bazel installs
                    # it as lib/<pkg>/lib<name>.so and dag files load it.
                    loadable = [t for t in owners if t.kind == 'cc_library']
                    for t in loadable:
                        if 'LOADABLE' not in t.flags:
                            t.flags.append('LOADABLE')
                        if t.output_name is None:
                            t.output_name = t.name if t.name.endswith('.so') else \
                                'lib%s.so' % t.name
                if not loadable:
                    self.warnings.append('%s: component %s (%s) is not in a loadable library'
                                         % (path, fq, rel))
                for t in loadable:
                    if fq not in t.components:
                        t.components.append(fq)
            # cmake target names
            short = path[len(SCAN_ROOT) + 1:] if path.startswith(SCAN_ROOT + '/') else path
            for t in pkg.targets:
                name = t.name
                if name.endswith('.so'):
                    name = name[:-3]
                    if name.startswith('lib'):
                        name = name[3:]
                base = '%s__%s' % (mangle(short.replace('/', '_')), mangle(name))
                cname = base
                k = 2
                while cname in used_names:
                    cname = '%s_%d' % (base, k)
                    k += 1
                used_names[cname] = t
                t.cmake_name = cname


def _dedupe(items):
    seen = set()
    out = []
    for item in items:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out


