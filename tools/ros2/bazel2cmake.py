# glob()
###############################################################################
def _glob_regex(pattern):
    out = ''
    i = 0
    segs = pattern.split('/')
    parts = []
    for seg in segs:
        if seg == '**':
            parts.append(None)
            continue
        rx = ''
        for ch in seg:
            if ch == '*':
                rx += '[^/]*'
            elif ch == '?':
                rx += '[^/]'
            else:
                rx += re.escape(ch)
        parts.append(rx)
    for idx, p in enumerate(parts):
        last = idx == len(parts) - 1
        if p is None:
            out += '(?:.*/)?' if not last else '.*'
        else:
            out += p + ('' if last else '/')
    del i
    return re.compile('^' + out + '$')


class Globber(object):
    def __init__(self, root):
        self.root = root
        self.cache = {}

    def files(self, pkg):
        if pkg in self.cache:
            return self.cache[pkg]
        base = os.path.join(self.root, pkg)
        files = []
        dirs = []
        for dirpath, dirnames, filenames in os.walk(base):
            rel = os.path.relpath(dirpath, base)
            rel = '' if rel == '.' else rel + '/'
            keep = []
            for d in sorted(dirnames):
                full = os.path.join(dirpath, d)
                if os.path.exists(os.path.join(full, 'BUILD')) or \
                        os.path.exists(os.path.join(full, 'BUILD.bazel')):
                    continue  # globs never cross package boundaries
                keep.append(d)
                dirs.append(rel + d)
            dirnames[:] = keep
            for f in sorted(filenames):
                files.append(rel + f)
        self.cache[pkg] = (sorted(files), sorted(dirs))
        return self.cache[pkg]

    def glob(self, pkg, include, exclude=(), exclude_directories=1):
        files, dirs = self.files(pkg)
        candidates = files if exclude_directories else files + dirs
        inc = [_glob_regex(p) for p in include]
        exc = [_glob_regex(p) for p in exclude]
        out = [f for f in candidates
               if any(r.match(f) for r in inc) and not any(r.match(f) for r in exc)]
        return sorted(set(out))


