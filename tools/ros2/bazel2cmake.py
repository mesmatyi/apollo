# Target model
###############################################################################
class Target(object):
    FIELDS = ('srcs', 'hdrs', 'deps', 'defines', 'local_defines', 'copts',
              'linkopts', 'includes', 'data')

    def __init__(self, kind, pkg, name):
        self.kind = kind
        self.pkg = pkg
        self.name = name
        self.aliases = []
        self.values = {f: [] for f in self.FIELDS}  # [(value, conds)]
        self.plugin_description = None
        self.output_name = None
        self.components = []
        self.flags = []
        self.broken = []
        self.optional_deps = []  # [(label, define)]
        self.cmake_name = None

    @property
    def label(self):
        return '//%s:%s' % (self.pkg, self.name)

    def add(self, field, value):
        for v, conds in _entries(value):
            if not isinstance(v, str):
                raise GenError('%s: non-string entry %r in %s' % (self.label, v, field))
            self.values[field].append((v, conds))


class Package(object):
    def __init__(self, path):
        self.path = path
        self.targets = []
        self.by_name = {}
        self.weak = {}
        self.plugin_descriptions = {}  # plugin label -> description label

    def add(self, target, extra_names=(), weak_names=()):
        """extra_names are hard aliases; weak_names (implicit outputs of
        Apollo's proto_library macro) give way to explicit targets."""
        for n in [target.name] + list(extra_names):
            if n in self.weak:
                owner = self.weak.pop(n)
                owner.aliases.remove(n)
                del self.by_name[n]
            if n in self.by_name:
                raise GenError('duplicate target //%s:%s' % (self.path, n))
            self.by_name[n] = target
        target.aliases.extend(extra_names)
        for n in weak_names:
            if n not in self.by_name:
                self.by_name[n] = target
                self.weak[n] = target
                target.aliases.append(n)
        self.targets.append(target)
        return target


