def undeclared_sdks(path):
    try:
        with open(path, encoding='utf-8', errors='replace') as f:
            text = f.read()
    except OSError:
        return []
    return sorted(set(UNDECLARED_SDK_INCLUDES[m.group(1)] for m in _SDK_INCLUDE.finditer(text)))


def uses_cuda_api(path):
    """True if a C++ source uses the CUDA API without a USE_GPU guard."""
    try:
        with open(path, encoding='utf-8', errors='replace') as f:
            text = f.read()
    except OSError:
        return False
    guards = ['USE_GPU'] + [d.split('=')[0] for opt in OPTIONAL_DEPS.values()
                            for d in opt.values()]
    return bool(_CUDA_API.search(text)) and not any(g in text for g in guards)


