# Proto analysis
###############################################################################
_PROTO_COMMENT = re.compile(r'//[^\n]*|/\*.*?\*/', re.S)
_PROTO_STRING = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'')
_PROTO_TOKEN = re.compile(r'[A-Za-z_][A-Za-z0-9_.]*|-?\d[\w.+-]*|"[^"]*"|\S')
_PROTO_IMPORT = re.compile(r'^\s*import\s+(?:public\s+|weak\s+)?"([^"]+)"\s*;', re.M)


def parse_proto(path):
    """Returns (imports, symbols) of a .proto file.

    symbols are the fully-qualified names the file adds to protobuf's pool:
    messages, enums, enum values (siblings of their enum), services.
    """
    with open(path, encoding='utf-8', errors='replace') as f:
        text = f.read()
    imports = _PROTO_IMPORT.findall(_PROTO_COMMENT.sub('', text))
    text = _PROTO_COMMENT.sub(' ', text)
    text = _PROTO_STRING.sub('""', text)
    tokens = _PROTO_TOKEN.findall(text)
    symbols = []
    package = ''
    stack = []  # (kind, scope_prefix)
    i = 0
    n = len(tokens)

    def prefix():
        for kind, scope in reversed(stack):
            if kind in ('message', 'file'):
                return scope
        return package

    while i < n:
        tok = tokens[i]
        kind = stack[-1][0] if stack else 'file'
        if tok == 'package' and not stack:
            package = tokens[i + 1]
            i += 2
            continue
        if tok in ('message', 'enum', 'service') and i + 2 < n and tokens[i + 2] == '{' \
                and kind in ('file', 'message'):
            name = (prefix() + '.' if prefix() else '') + tokens[i + 1]
            symbols.append(name)
            if tok == 'message':
                stack.append(('message', name))
            elif tok == 'enum':
                stack.append(('enum', prefix()))
            else:
                stack.append(('service', name))
            i += 3
            continue
        if tok == 'oneof' and i + 2 < n and tokens[i + 2] == '{':
            stack.append(('oneof', prefix()))
            i += 3
            continue
        if tok == '{':
            stack.append(('block', prefix()))
            i += 1
            continue
        if tok == '}':
            if stack:
                stack.pop()
            i += 1
            continue
        if kind == 'enum' and re.match(r'^[A-Za-z_]\w*$', tok) and tok not in ('option', 'reserved') \
                and i + 1 < n and tokens[i + 1] == '=':
            scope = stack[-1][1]
            symbols.append((scope + '.' if scope else '') + tok)
            # skip to ';'
            while i < n and tokens[i] != ';':
                if tokens[i] == '[':
                    depth = 0
                    while i < n:
                        if tokens[i] == '[':
                            depth += 1
                        elif tokens[i] == ']':
                            depth -= 1
                            if depth == 0:
                                break
                        i += 1
                i += 1
            continue
        i += 1
    return imports, symbols


def mangle(text):
    return re.sub(r'[^A-Za-z0-9_]', '_', text)


def proto_lib_name(path):
    return 'apollo_proto_' + mangle(os.path.splitext(path)[0])


def analyze_protos(root):
    files = []
    for dirpath, dirnames, filenames in os.walk(os.path.join(root, SCAN_ROOT)):
        dirnames.sort()
        for f in sorted(filenames):
            if f.endswith('.proto'):
                files.append(os.path.relpath(os.path.join(dirpath, f), root))
    files.sort()
    imports = {}
    owners = collections.defaultdict(set)
    for f in files:
        imp, syms = parse_proto(os.path.join(root, f))
        imports[f] = imp
        for s in syms:
            owners[s].add(f)
    conflicts = collections.defaultdict(set)
    for s, fs in owners.items():
        if len(fs) > 1:
            for f in fs:
                conflicts[f].update(fs - {f})
    isolated = set(conflicts)
    changed = True
    while changed:
        changed = False
        for f in files:
            if f not in isolated and any(i in isolated for i in imports[f]):
                isolated.add(f)
                changed = True
    lib = {f: (proto_lib_name(f) if f in isolated else 'apollo_proto') for f in files}
    return files, imports, lib, conflicts


