def cmake_quote(value):
    if value == '':
        return '""'
    if re.match(r'^[A-Za-z0-9_./:+=@,!?-]+$', value) and not value.startswith('#'):
        return value
    v = value.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace(';', '\\;')
    return '"%s"' % v


def entry_text(value, conds):
    if conds:
        return cmake_quote('%s?%s' % (','.join(conds), value))
    return cmake_quote(value)


FIELD_KEYWORDS = [('srcs', 'SRCS'), ('hdrs', 'HDRS'), ('deps', 'DEPS'),
                  ('defines', 'DEFINES'), ('local_defines', 'LOCAL_DEFINES'),
                  ('copts', 'COPTS'), ('linkopts', 'LINKOPTS'),
                  ('includes', 'INCLUDES'), ('data', 'DATA')]


def emit_package(pkg):
    out = io.StringIO()
    out.write(HEADER.format(src=pkg.path + '/BUILD'))
    out.write('apollo_bazel_package(%s)\n' % pkg.path)
    for t in pkg.targets:
        out.write('\napollo_target(%s %s\n' % (t.kind, cmake_quote(t.name)))
        out.write('  TARGET %s\n' % t.cmake_name)
        if t.aliases:
            out.write('  ALIASES %s\n' % ' '.join(cmake_quote(a) for a in t.aliases))
        if t.output_name:
            out.write('  OUTPUT_NAME %s\n' % cmake_quote(t.output_name))
        if t.plugin_description:
            out.write('  PLUGIN_DESCRIPTION %s\n' % cmake_quote(t.plugin_description))
        for field, kw in FIELD_KEYWORDS:
            vals = t.values[field]
            if not vals:
                continue
            if len(vals) == 1:
                out.write('  %s %s\n' % (kw, entry_text(*vals[0])))
            else:
                out.write('  %s\n' % kw)
                for v, conds in vals:
                    out.write('    %s\n' % entry_text(v, conds))
        if t.optional_deps:
            out.write('  OPTIONAL_DEPS %s\n' % ' '.join(
                '%s %s' % (cmake_quote(d), cmake_quote(df)) for d, df in t.optional_deps))
        if t.components:
            out.write('  COMPONENTS %s\n' % ' '.join(cmake_quote(c) for c in t.components))
        if t.flags:
            out.write('  FLAGS %s\n' % ' '.join(cmake_quote(c) for c in t.flags))
        if t.broken:
            out.write('  BROKEN %s\n' % cmake_quote('; '.join(sorted(set(t.broken)))))
        out.write(')\n')
    return out.getvalue()


def emit_packages_index(paths):
    out = io.StringIO()
    out.write(HEADER.format(src='modules/**/BUILD'))
    out.write('set(APOLLO_BAZEL_PACKAGES\n')
    for p in paths:
        out.write('  %s\n' % p)
    out.write(')\n')
    return out.getvalue()


def emit_protos(files, imports, lib, conflicts):
    out = io.StringIO()
    out.write(HEADER.format(src='modules/**/*.proto'))
    out.write('# apollo_proto_file(<file> <library> [imports...])\n')
    out.write('# Files in a library other than apollo_proto define symbols that\n'
              '# clash with another file (or import such a file):\n')
    for f in files:
        if f in conflicts:
            out.write('#   %s <-> %s\n' % (f, ' '.join(sorted(conflicts[f]))))
    out.write('\n')
    for f in files:
        imps = [i for i in imports[f]]
        out.write('apollo_proto_file(%s %s%s)\n' % (
            f, lib[f], ''.join(' ' + cmake_quote(i) for i in imps)))
    return out.getvalue()


def find_build_files(root):
    out = []
    for dirpath, dirnames, filenames in os.walk(os.path.join(root, SCAN_ROOT)):
        dirnames.sort()
        if 'BUILD' in filenames:
            out.append(os.path.relpath(dirpath, root))
    return sorted(out)


def generate(root):
    globber = Globber(root)
    ev = Evaluator(root, globber)
    model = Model(root)
    for path in find_build_files(root):
        model.add_package(ev.evaluate(path))
    files, imports, lib, conflicts = analyze_protos(root)
    model.finalize(lib)
    outputs = {}
    emitted = []
    for path in sorted(model.packages):
        pkg = model.packages[path]
        target_file = os.path.join(path, GEN_FILE_NAME)
        if not pkg.targets:
            continue
        outputs[target_file] = emit_package(pkg)
        emitted.append(path)
    outputs[os.path.join(GEN_DIR, 'apollo_packages.cmake')] = emit_packages_index(emitted)
    outputs[os.path.join(GEN_DIR, 'apollo_protos.cmake')] = emit_protos(files, imports, lib, conflicts)
    return outputs, ev.warnings + model.warnings, model


def stale_outputs(root, outputs):
    """Generated files on disk that the generator would no longer produce."""
    stale = []
    for dirpath, dirnames, filenames in os.walk(os.path.join(root, SCAN_ROOT)):
        dirnames.sort()
        if GEN_FILE_NAME in filenames:
            rel = os.path.relpath(os.path.join(dirpath, GEN_FILE_NAME), root)
            if rel not in outputs:
                with open(os.path.join(root, rel), encoding='utf-8') as f:
                    if f.readline().startswith('# Generated by tools/ros2/bazel2cmake.py'):
                        stale.append(rel)
    return stale


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--root', default=REPO_ROOT, help='repository root')
    parser.add_argument('--check', action='store_true',
                        help='do not write; exit 1 if any output is out of date')
    parser.add_argument('-v', '--verbose', action='store_true', help='print warnings')
    args = parser.parse_args()
    root = os.path.abspath(args.root)
    try:
        outputs, warnings, model = generate(root)
    except GenError as e:
        print('bazel2cmake: error: %s' % e, file=sys.stderr)
        return 2
    changed = []
    for rel, content in sorted(outputs.items()):
        path = os.path.join(root, rel)
        old = None
        if os.path.exists(path):
            with open(path, encoding='utf-8') as f:
                old = f.read()
        if old != content:
            changed.append(rel)
            if not args.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, 'w', encoding='utf-8') as f:
                    f.write(content)
    stale = stale_outputs(root, outputs)
    if not args.check:
        for rel in stale:
            os.remove(os.path.join(root, rel))
    if args.verbose:
        for w in warnings:
            print('warning: %s' % w, file=sys.stderr)
    ntargets = sum(len(p.targets) for p in model.packages.values())
    kinds = collections.Counter(t.kind for p in model.packages.values() for t in p.targets)
    print('bazel2cmake: %d packages, %d targets (%s); %d outputs %s, %d stale %s; %d warnings'
          % (len(model.packages), ntargets,
             ', '.join('%s %d' % kv for kv in sorted(kinds.items())),
             len(changed), 'out of date' if args.check else 'written',
             len(stale), 'present' if args.check else 'removed', len(warnings)))
    if args.check and (changed or stale):
        for rel in changed + stale:
            print('  stale: %s' % rel)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
