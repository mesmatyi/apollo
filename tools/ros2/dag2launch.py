class LaunchModule(object):

    def __init__(self):
        self.name = ''
        self.settings = {}  # first occurrence of each scalar tag, like get_param_value()
        self.dags = []  # [(dag_conf text, [comments])]
        self.plugins = []
        self.extra_args = None
        self.comments = []
        self.other = []  # [(tag, text)] tags cyber_launch does not know

    def get(self, key, default=''):
        return self.settings.get(key, default)


class LaunchFile(object):

    def __init__(self):
        self.desc = ''
        self.version = ''
        self.environment = []
        self.modules = []
        self.comments = []  # file-level comments
        self.other = []


_MODULE_SCALARS = ('process_name', 'type', 'sched_name', 'exception_handler', 'respawn_limit',
                   'cpuprofile', 'memprofile', 'nice')


def _comment_text(text):
    lines = [line.strip() for line in (text or '').strip().splitlines()]
    return '\n'.join(lines)


def parse_launch(data):
    """Parses a cyber_launch XML document (bytes). Returns None if the root
    element is not <cyber> (e.g. ROS 1 launch files)."""
    builder = ET.TreeBuilder(insert_comments=True)
    parser = ET.XMLParser(target=builder)
    parser.feed(data)
    root = parser.close()
    if root.tag != 'cyber':
        return None
    lf = LaunchFile()
    text = data.decode('utf-8', 'replace')
    prolog = text[:text.find('<cyber')] if '<cyber' in text else ''
    lf.comments.extend(_comment_text(c) for c in re.findall(r'<!--(.*?)-->', prolog, re.S))
    pending = []
    for child in root:
        if child.tag is ET.Comment:
            pending.append(_comment_text(child.text))
            continue
        if child.tag == 'module':
            module = _parse_module(child)
            module.comments[:0] = pending
            lf.modules.append(module)
        else:
            lf.comments.extend(pending)
            if child.tag == 'desc':
                lf.desc = (child.text or '').strip()
            elif child.tag == 'version':
                lf.version = (child.text or '').strip()
            elif child.tag == 'environment':
                for var in child:
                    if var.tag is not ET.Comment:
                        lf.environment.append((var.tag, (var.text or '').strip()))
            else:
                lf.other.append((child.tag, ' '.join((child.text or '').split())))
        pending = []
    lf.comments.extend(pending)
    return lf


def _parse_module(elem):
    module = LaunchModule()
    module.extra_args = elem.attrib.get('extra_args')
    pending = []
    for child in elem:
        if child.tag is ET.Comment:
            pending.append(_comment_text(child.text))
            continue
        value = (child.text or '').strip()
        if child.tag == 'dag_conf':
            if value:  # get_param_list() skips empty entries
                module.dags.append((value, pending))
                pending = []
            continue
        module.comments.extend(pending)
        pending = []
        if child.tag == 'name':
            module.name = value
        elif child.tag in _MODULE_SCALARS:
            module.settings.setdefault(child.tag, value)
        elif child.tag == 'plugin':
            if value:
                module.plugins.append(value)
        elif child.tag == 'version':
            pass  # informational only
        else:
            module.other.append((child.tag, ' '.join(value.split())))
    module.comments.extend(pending)
    return module


