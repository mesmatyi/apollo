class DagComponent(object):
    """One components/timer_components entry of a dag."""

    def __init__(self, kind, class_name, config, module_library):
        self.kind = kind  # 'components' | 'timer_components'
        self.class_name = class_name
        self.config = config
        self.module_library = module_library
        self.plugin = class_name
        self.package = 'apollo'  # colcon package that installs the component
        self.resolution = None  # Resolution

    @property
    def name(self):
        return self.config.scalar('name', '')

    @property
    def node_name(self):
        return to_node_name(self.name)


class Dag(object):

    def __init__(self, path):
        self.path = path  # repository-relative (or absolute when outside it)
        self.components = []
        self.error = None


Resolution = collections.namedtuple('Resolution', 'fq status detail')
# status: 'exact'      registered in the module_library directory
#         'fallback'   registered elsewhere (subdirectory / unique in the repo)
#         'unresolved' not found or ambiguous


class ClassResolver(object):
    """Maps (class_name, module_library) to the fully-qualified class name with
    apollo_ros2_common.find_registered_components()."""

    def __init__(self, root):
        self.root = root
        self._scans = {}
        self._index = None

    def _scan(self, directory, recursive=False):
        key = (directory, recursive)
        if key not in self._scans:
            # os.walk() order depends on the file system: sort for determinism
            self._scans[key] = sorted(find_registered_components(directory, recursive=recursive),
                                      key=lambda entry: entry[2])
        return self._scans[key]

    def _repo_index(self):
        if self._index is None:
            self._index = []
            for d in INDEX_DIRS:
                path = os.path.join(self.root, d)
                if os.path.isdir(path):
                    self._index.extend(self._scan(path, recursive=True))
        return self._index

    def rel(self, path):
        return os.path.relpath(path, self.root).replace(os.sep, '/')

    def library_dir(self, module_library):
        """Repository-relative Bazel package directory of a module_library, or
        None when it cannot be mapped into the repository."""
        lib = module_library.strip()
        if lib.startswith('/apollo/'):
            lib = lib[len('/apollo/'):]
        if lib.startswith('bazel-bin/'):
            lib = lib[len('bazel-bin/'):]
        if os.path.isabs(lib):
            lib = os.path.relpath(lib, self.root)
            if lib.startswith('..'):
                return None
        lib = os.path.normpath(lib)
        if lib.startswith('..'):
            return None
        return os.path.dirname(lib).replace(os.sep, '/')

    @staticmethod
    def _matches(entries, class_name):
        wanted = re.sub(r'\s+', '', class_name.lstrip(':'))
        base = wanted.split('<', 1)[0]
        short = base.split('::')[-1] + wanted[len(base):]
        found = collections.OrderedDict()
        for cls, fq, path in entries:
            if cls != short:
                continue
            if '::' in base and fq != wanted and not fq.endswith('::' + wanted):
                continue
            found.setdefault(fq, path)
        return found

    def resolve(self, class_name, module_library):
        libdir = self.library_dir(module_library)
        where = libdir if libdir is not None else module_library
        if libdir is not None:
            directory = os.path.join(self.root, libdir)
            found = self._matches(self._scan(directory), class_name)
            if len(found) == 1:
                return Resolution(next(iter(found)), 'exact', None)
            if len(found) > 1:
                return Resolution(None, 'unresolved', 'ambiguous in %s: %s' % (
                    where, ', '.join(sorted(found))))
            if os.path.isdir(directory):
                found = self._matches(self._scan(directory, recursive=True), class_name)
                if len(found) == 1:
                    fq, path = next(iter(found.items()))
                    return Resolution(fq, 'fallback', 'not registered in %s/ itself; found in %s'
                                      % (where, self.rel(path)))
        found = self._matches(self._repo_index(), class_name)
        if len(found) == 1:
            fq, path = next(iter(found.items()))
            return Resolution(fq, 'fallback', 'not registered in %s/; found in %s'
                              % (where, self.rel(path)))
        if len(found) > 1:
            candidates = ', '.join('%s (%s)' % (fq, self.rel(p)) for fq, p in sorted(found.items()))
            return Resolution(None, 'unresolved', 'not registered in %s/ and ambiguous in the '
                              'repository: %s' % (where, candidates))
        hint = ''
        if '<' in class_name:
            hint = ' (a class template instance, probably registered through a wrapper macro)'
        return Resolution(None, 'unresolved', 'CYBER_REGISTER_COMPONENT(%s) not found in %s/ '
                          'nor anywhere in %s%s' % (class_name, where,
                                                    '/, '.join(INDEX_DIRS) + '/', hint))


def load_dag(path, label, resolver):
    """Parses and validates a dag file and resolves its class names."""
    dag = Dag(label)
    try:
        with open(path, encoding='utf-8') as f:
            msg = parse_text_proto(f.read())
        _validate(msg, 'DagConfig')
    except (OSError, UnicodeDecodeError, TextFormatError) as e:
        dag.error = str(e)
        return dag
    for module in msg.get_all('module_config'):
        library = module.scalar('module_library', '')
        # mainboard loads the components of a module_config before its timer components
        for kind in ('components', 'timer_components'):
            for info in module.get_all(kind):
                class_name = info.scalar('class_name', '')
                comp = DagComponent(kind, class_name, info.get('config') or Message(), library)
                libdir = resolver.library_dir(library) or ''
                if libdir == 'cyber' or libdir.startswith('cyber/'):
                    comp.package = 'cyber'  # components built by the `cyber` package
                if not class_name:
                    comp.resolution = Resolution(None, 'unresolved', 'empty class_name')
                else:
                    comp.resolution = resolver.resolve(class_name, library)
                    if comp.resolution.fq:
                        comp.plugin = comp.resolution.fq
                dag.components.append(comp)
    if not dag.components:
        dag.error = 'no components or timer_components'
    return dag


