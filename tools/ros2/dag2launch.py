class TextFormatError(ValueError):
    pass


Scalar = collections.namedtuple('Scalar', 'kind text value')


class Message(object):
    """A parsed text-format message: an ordered list of (field, value) pairs,
    where value is a Message or a Scalar."""

    __slots__ = ('fields',)

    def __init__(self, fields=None):
        self.fields = list(fields or [])

    def get(self, name, default=None):
        for field, value in reversed(self.fields):
            if field == name:
                return value
        return default

    def get_all(self, name):
        return [value for field, value in self.fields if field == name]

    def scalar(self, name, default=None):
        value = self.get(name)
        return default if value is None or isinstance(value, Message) else value.value

    def to_text(self, top_level=True):
        """Serializes to text format: one field per line at the top level,
        nested messages on a single line."""
        parts = []
        for field, value in self.fields:
            if isinstance(value, Message):
                inner = value.to_text(top_level=False)
                parts.append('%s { %s }' % (field, inner) if inner else '%s {}' % field)
            else:
                parts.append('%s: %s' % (field, _format_scalar(value)))
        return ('\n' if top_level else ' ').join(parts)


_TOKEN_RE = re.compile(r'''
    (?P<space>\s+)
  | (?P<comment>\#[^\n]*)
  | (?P<string>"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*')
  | (?P<number>[-+]?(?:0[xX][0-9A-Fa-f]+|(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?[fF]?)
                (?![A-Za-z0-9_]))
  | (?P<ident>-?[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*)
  | (?P<punct>[:{}<>\[\],;])
''', re.X)

_SIMPLE_ESCAPES = {
    'n': b'\n', 't': b'\t', 'r': b'\r', 'a': b'\a', 'b': b'\b', 'f': b'\f',
    'v': b'\v', '\\': b'\\', "'": b"'", '"': b'"', '?': b'?',
}


def _tokenize(text):
    tokens = []
    pos, line = 0, 1
    while pos < len(text):
        m = _TOKEN_RE.match(text, pos)
        if not m:
            raise TextFormatError('line %d: unexpected character %r' % (line, text[pos]))
        if m.lastgroup not in ('space', 'comment'):
            tokens.append((m.lastgroup, m.group(), line))
        line += m.group().count('\n')
        pos = m.end()
    return tokens, line


def _unescape(body, line):
    out = bytearray()
    i, n = 0, len(body)
    while i < n:
        c = body[i]
        if c != '\\':
            out += c.encode('utf-8', 'surrogateescape')
            i += 1
            continue
        i += 1
        c = body[i] if i < n else ''
        if c in _SIMPLE_ESCAPES:
            out += _SIMPLE_ESCAPES[c]
            i += 1
            continue
        m = None
        if c and c in '01234567':
            m = re.compile(r'[0-7]{1,3}').match(body, i)
            out.append(int(m.group(), 8) & 0xff)
        elif c in ('x', 'X'):
            m = re.compile(r'[0-9A-Fa-f]{1,2}').match(body, i + 1)
            if m:
                out.append(int(m.group(), 16))
        elif c in ('u', 'U'):
            m = re.compile(r'[0-9A-Fa-f]{%d}' % (4 if c == 'u' else 8)).match(body, i + 1)
            if m:
                out += chr(int(m.group(), 16)).encode('utf-8', 'surrogatepass')
        if not m:
            raise TextFormatError('line %d: invalid escape sequence "\\%s"' % (line, c))
        i = m.end()
    return out.decode('utf-8', 'surrogateescape')


def _escape(value):
    out = []
    for ch in value:
        code = ord(ch)
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        elif code < 0x20 or code == 0x7f:
            out.append('\\%03o' % code)
        elif 0xdc80 <= code <= 0xdcff:  # raw byte kept by surrogateescape
            out.append('\\%03o' % (code - 0xdc00))
        else:
            out.append(ch)
    return '"%s"' % ''.join(out)


def _format_scalar(scalar):
    return _escape(scalar.value) if scalar.kind == 'string' else scalar.text


class _TextParser(object):

    def __init__(self, text):
        self.tokens, self.last_line = _tokenize(text)
        self.pos = 0

    def peek(self):
        if self.pos < len(self.tokens):
            return self.tokens[self.pos]
        return (None, '<end of file>', self.last_line)

    def error(self, msg):
        return TextFormatError('line %d: %s' % (self.peek()[2], msg))

    def is_punct(self, chars):
        kind, text, _ = self.peek()
        return kind == 'punct' and text in chars

    def message(self, close=None):
        msg = Message()
        while True:
            kind, text, _ = self.peek()
            if kind is None:
                if close:
                    raise self.error('expected "%s"' % close)
                return msg
            if close and kind == 'punct' and text == close:
                self.pos += 1
                return msg
            if kind != 'ident' or text.startswith('-'):
                raise self.error('expected a field name, got %r' % text)
            self.pos += 1
            name = text
            colon = self.is_punct(':')
            if colon:
                self.pos += 1
            if self.is_punct('{<'):
                msg.fields.append((name, self.value()))
            elif self.is_punct('['):
                if not colon:
                    raise self.error('expected ":" after "%s"' % name)
                self.pos += 1
                while not self.is_punct(']'):
                    msg.fields.append((name, self.value()))
                    if self.is_punct(','):
                        self.pos += 1
                    elif not self.is_punct(']'):
                        raise self.error('expected "," or "]"')
                self.pos += 1
            elif not colon:
                raise self.error('expected ":" or "{" after "%s"' % name)
            else:
                msg.fields.append((name, self.value()))
            if self.is_punct(',;'):
                self.pos += 1

    def value(self):
        kind, text, line = self.peek()
        if kind == 'punct' and text in '{<':
            self.pos += 1
            return self.message('}' if text == '{' else '>')
        if kind == 'string':
            parts = []
            while self.peek()[0] == 'string':
                _, text, line = self.peek()
                parts.append(_unescape(text[1:-1], line))
                self.pos += 1
            return Scalar('string', None, ''.join(parts))
        if kind in ('number', 'ident'):
            self.pos += 1
            return Scalar(kind, text, text)
        raise self.error('expected a value, got %r' % text)


def parse_text_proto(text):
    """Parses protobuf text format into a Message (no schema)."""
    return _TextParser(text).message()


# Schema of cyber/proto/dag_conf.proto, component_conf.proto, qos_profile.proto
_STRING, _UINT = 'string', 'uint32'
_ENUMS = {
    'QosHistoryPolicy': ('HISTORY_SYSTEM_DEFAULT', 'HISTORY_KEEP_LAST', 'HISTORY_KEEP_ALL'),
    'QosReliabilityPolicy': ('RELIABILITY_SYSTEM_DEFAULT', 'RELIABILITY_RELIABLE',
                             'RELIABILITY_BEST_EFFORT'),
    'QosDurabilityPolicy': ('DURABILITY_SYSTEM_DEFAULT', 'DURABILITY_TRANSIENT_LOCAL',
                            'DURABILITY_VOLATILE'),
}
_SCHEMA = {
    'DagConfig': {'module_config': ('ModuleConfig', True)},
    'ModuleConfig': {
        'module_library': (_STRING, False),
        'components': ('ComponentInfo', True),
        'timer_components': ('TimerComponentInfo', True),
    },
    'ComponentInfo': {'class_name': (_STRING, False), 'config': ('ComponentConfig', False)},
    'TimerComponentInfo': {
        'class_name': (_STRING, False), 'config': ('TimerComponentConfig', False)},
    'ComponentConfig': {
        'name': (_STRING, False),
        'config_file_path': (_STRING, False),
        'flag_file_path': (_STRING, False),
        'readers': ('ReaderOption', True),
    },
    'TimerComponentConfig': {
        'name': (_STRING, False),
        'config_file_path': (_STRING, False),
        'flag_file_path': (_STRING, False),
        'interval': (_UINT, False),
    },
    'ReaderOption': {
        'channel': (_STRING, False),
        'qos_profile': ('QosProfile', False),
        'pending_queue_size': (_UINT, False),
    },
    'QosProfile': {
        'history': ('QosHistoryPolicy', False),
        'depth': (_UINT, False),
        'mps': (_UINT, False),
        'reliability': ('QosReliabilityPolicy', False),
        'durability': ('QosDurabilityPolicy', False),
    },
}
_UINT_RE = re.compile(r'\+?(?:0[xX][0-9A-Fa-f]+|\d+)')


def _validate(msg, type_name, where=''):
    """Checks a parsed message against the Cyber dag schema, the way the C++
    text-format parser used by mainboard would."""
    schema = _SCHEMA[type_name]
    seen = set()
    for name, value in msg.fields:
        path = where + name
        if name not in schema:
            raise TextFormatError('unknown field "%s" in %s' % (path, type_name))
        ftype, repeated = schema[name]
        if not repeated and name in seen:
            raise TextFormatError('non-repeated field "%s" is specified multiple times' % path)
        seen.add(name)
        if ftype in _SCHEMA:
            if not isinstance(value, Message):
                raise TextFormatError('field "%s" must be a message' % path)
            _validate(value, ftype, path + '.')
        elif isinstance(value, Message):
            raise TextFormatError('field "%s" must be a %s, not a message' % (path, ftype))
        elif ftype == _STRING:
            if value.kind != 'string':
                raise TextFormatError('field "%s" expects a string, got %s' % (path, value.text))
        elif ftype == _UINT:
            if value.kind != 'number' or not _UINT_RE.fullmatch(value.text):
                raise TextFormatError('field "%s" expects an unsigned integer, got %s'
                                      % (path, value.text or repr(value.value)))
        else:  # enum
            ok = (value.kind == 'ident' and value.text in _ENUMS[ftype]) or (
                value.kind == 'number' and value.text.isdigit()
                and int(value.text) < len(_ENUMS[ftype]))
            if not ok:
                raise TextFormatError('field "%s" expects a %s value, got %s'
                                      % (path, ftype, value.text or repr(value.value)))


