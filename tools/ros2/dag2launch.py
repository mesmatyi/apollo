_RUNNER_DESCRIPTION = 'container: component_container_mt per process; mainboard: Cyber dag runner'


def _py(value):
    """Deterministic Python literal for a str."""
    return repr(value)


def _docstring_line(line):
    return line.replace('\\', '\\\\').replace('"""', "'''")


def _comment_lines(text, indent):
    out = []
    for line in text.splitlines() or ['']:
        out.append((indent + '# ' + line).rstrip())
    return out


class _Writer(object):

    def __init__(self):
        self.lines = []
        self.names = set()  # imported names in use

    def use(self, *names):
        self.names.update(names)

    def line(self, text=''):
        self.lines.append(text.rstrip())

    def comment(self, text, indent):
        self.lines.extend(_comment_lines(text, indent))


class Renderer(object):
    """Renders the Python launch file for a list of processes."""

    def __init__(self, source, kind, title, docs, processes, launch_file=None):
        self.source = source
        self.kind = kind  # 'dag' | 'launch'
        self.title = title
        self.docs = docs
        self.processes = processes
        self.launch_file = launch_file
        self.helpers = set()
        self.w = _Writer()

    # -- top level ------------------------------------------------------------

    def render(self):
        body = self._body()
        out = []
        out.append('%s from %s.' % (MARKER, self.source))
        out.append('# DO NOT EDIT: change the source file and re-run %s' % TOOL)
        out.append('# (tools/ros2/dag2launch.py --check verifies that this file is up to date).')
        out.append('"""%s' % _docstring_line(self.title))
        if self.docs:
            out.append('')
            out.extend(_docstring_line(line) for line in self.docs)
        out.append('"""')
        out.append('')
        out.append('import os')
        if 'apollo_executable' in self.helpers:
            out.append('import shutil')
        out.append('')
        for module, names in _IMPORT_ORDER:
            used = [n for n in names if n in self.w.names]
            if used:
                out.append('from %s import %s' % (module, ', '.join(used)))
        for helper, code in (('apollo_file', _HELPER_APOLLO_FILE),
                             ('apollo_arg', _HELPER_APOLLO_ARG),
                             ('apollo_executable', _HELPER_APOLLO_EXECUTABLE),
                             ('reload_on_start', _HELPER_RELOAD_ON_START)):
            if helper in self.helpers:
                out.append('')
                out.extend(code.rstrip('\n').split('\n'))
        out.append('')
        out.append('')
        out.extend(body)
        return '\n'.join(out) + '\n'

    def _body(self):
        w = self.w
        w.use('LaunchDescription')
        w.line('def generate_launch_description():')
        w.line('    ld = LaunchDescription()')
        libraries = [p for p in self.processes if p.kind == 'library']
        if libraries:
            w.use('DeclareLaunchArgument', 'LaunchConfiguration', 'IfCondition',
                  'EqualsSubstitution')
            w.line('    ld.add_action(DeclareLaunchArgument(')
            w.line("        'runner', default_value='container',")
            w.line("        choices=['container', 'mainboard'],")
            w.line('        description=%s))' % _py(_RUNNER_DESCRIPTION))
            w.line("    runner = LaunchConfiguration('runner')")
            w.line("    in_container = IfCondition(EqualsSubstitution(runner, 'container'))")
            w.line("    in_mainboard = IfCondition(EqualsSubstitution(runner, 'mainboard'))")
        lf = self.launch_file
        if lf is not None:
            for comment in lf.comments:
                w.line()
                w.comment(comment, '    ')
            for tag, text in lf.other:
                w.comment('<%s>%s</%s> (not used by cyber_launch)' % (tag, text, tag), '    ')
            if lf.environment:
                w.use('SetEnvironmentVariable')
                w.line()
                w.line('    # <environment>')
                for name, value in lf.environment:
                    w.line('    ld.add_action(SetEnvironmentVariable(%s, %s))'
                           % (_py(name), _py(value)))
        for index, proc in enumerate(self.processes):
            w.line()
            if proc.kind == 'binary':
                self._binary(proc)
            else:
                self._library(proc, index)
        w.line('    return ld')
        return w.lines

    # -- processes ------------------------------------------------------------

    def _process_banner(self, proc):
        w = self.w
        w.line('    # ' + '-' * 72)
        if self.kind == 'dag':
            w.line('    # dag %s' % self.source)
        else:
            modules = ', '.join(m.name or '<unnamed>' for m in proc.modules)
            what = 'binary' if proc.kind == 'binary' else 'process %s' % _py(proc.label)
            plural = 's' if len(proc.modules) > 1 else ''
            w.line('    # %s  (module%s: %s)' % (what, plural, modules))
        w.line('    # ' + '-' * 72)
        for module in proc.modules:
            for comment in module.comments:
                w.comment(comment, '    ')
            for tag, text in module.other:
                w.comment('<%s>%s</%s>' % (tag, text, tag), '    ')
        for note in proc.notes:
            w.comment(note, '    ')

    def _exception_kwargs(self, proc):
        handler = proc.setting('exception_handler')
        if handler == 'respawn':
            limit = proc.setting('respawn_limit')
            limit = int(limit) if limit.isdigit() else DEFAULT_RESPAWN_LIMIT
            return ['respawn=True', 'respawn_max_retries=%d' % limit]
        if handler == 'exit':
            self.w.use('Shutdown')
            reason = 'process %s exited (cyber_launch exception_handler: exit)' % proc.label
            return ['on_exit=[Shutdown(reason=%s)]' % _py(reason)]
        return []

    def _binary(self, proc):
        w = self.w
        self._process_banner(proc)
        handler = proc.setting('exception_handler')
        if handler and handler not in ('respawn', 'exit'):
            w.line('    # exception_handler %s is not handled by cyber_launch' % _py(handler))
        w.use('ExecuteProcess')
        self.helpers.update(('apollo_executable', 'apollo_file'))
        args = ['apollo_executable(%s)' % _py(proc.cmd[0])]
        for arg in proc.cmd[1:]:
            if '/apollo/' in arg:
                self.helpers.add('apollo_arg')
                args.append('apollo_arg(%s)' % _py(arg))
            else:
                args.append(_py(arg))
        w.line('    ld.add_action(ExecuteProcess(')
        w.line('        name=%s,' % _py(proc.modules[0].name or os.path.basename(proc.cmd[0])))
        w.line('        cmd=[')
        for arg in args:
            w.line('            %s,' % arg)
        w.line('        ],')
        w.line("        output='screen',")
        for kw in self._exception_kwargs(proc):
            w.line('        %s,' % kw)
        w.lines[-1] = w.lines[-1][:-1] + '))'

    def _library(self, proc, index):
        w = self.w
        self._process_banner(proc)
        handler = proc.setting('exception_handler')
        if handler and handler not in ('respawn', 'exit'):
            w.line('    # exception_handler %s is not handled by cyber_launch' % _py(handler))
        sched = proc.setting('sched_name', DEFAULT_SCHED_NAME)
        if sched != DEFAULT_SCHED_NAME:
            w.line('    # sched_name %s: Cyber scheduler policy, only used with runner:=mainboard'
                   % _py(sched))
        for key in ('cpuprofile', 'memprofile'):
            if proc.setting(key):
                w.line('    # %s %s: only used with runner:=mainboard'
                       % (key, _py(proc.setting(key))))
        if proc.plugins:
            w.line('    # plugins (--plugin) are only passed with runner:=mainboard; the container')
            w.line('    # relies on the plugin index (APOLLO_PLUGIN_INDEX_PATH): %s'
                   % ', '.join(proc.plugins))
        if proc.setting('nice'):
            w.line('    # nice %s: cyber_launch reniced the process (sudo renice); not applied'
                   % _py(proc.setting('nice')))
        if proc.extra_args_note:
            w.line('    # extra_args %s: only used with runner:=mainboard'
                   % _py(proc.extra_args_note))
        exception_kwargs = self._exception_kwargs(proc)
        respawn = any(kw.startswith('respawn=') for kw in exception_kwargs)
        container_name = proc.container_name

        w.use('ComposableNodeContainer')
        nodes_indent = '        ' if respawn else '            '
        if respawn:
            var = 'container_%d' % index
            w.line('    %s = ComposableNodeContainer(' % var)
        else:
            w.line('    ld.add_action(ComposableNodeContainer(')
        w.line('        condition=in_container,')
        w.line("        package='rclcpp_components',")
        w.line("        executable='component_container_mt',")
        w.line('        exec_name=%s,' % _py(proc.label))
        w.line('        name=%s,' % _py(container_name))
        w.line("        namespace='',")
        w.line("        output='screen',")
        for kw in exception_kwargs:
            w.line('        %s,' % kw)
        if respawn:
            w.lines[-1] = w.lines[-1][:-1] + ')'
            w.line('    ld.add_action(%s)' % var)
            w.line('    # exception_handler respawn: the components are loaded on every (re)start')
            w.use('RegisterEventHandler', 'OnProcessStart', 'LoadComposableNodes', 'TimerAction')
            self.helpers.add('reload_on_start')
            w.line('    ld.add_action(reload_on_start(%s, [' % var)
        else:
            w.line('        composable_node_descriptions=[')
        self._composable_nodes(proc, nodes_indent)
        if respawn:
            w.line('    ]))')
        else:
            w.line('        ]))')

        # runner:=mainboard
        w.use('Node')
        w.line('    ld.add_action(Node(')
        w.line('        condition=in_mainboard,')
        w.line("        package='cyber',")
        w.line("        executable='mainboard',")
        w.line('        exec_name=%s,' % _py(proc.label))
        w.line("        output='screen',")
        for kw in exception_kwargs:
            w.line('        %s,' % kw)
        w.line('        arguments=[')
        for group in self._mainboard_args(proc):
            w.line('            %s,' % ', '.join(group))
        w.line('        ]))')

    def _dag_path_expr(self, ref):
        if ref.relpath is not None:
            self.helpers.add('apollo_file')
            return 'apollo_file(%s)' % _py(ref.relpath)
        return _py(ref.text)

    def _arg_expr(self, arg):
        if '/apollo/' in arg:
            self.helpers.update(('apollo_arg', 'apollo_file'))
            return 'apollo_arg(%s)' % _py(arg)
        return _py(arg)

    def _mainboard_args(self, proc):
        """Arguments exactly as cyber_launch passed them to mainboard."""
        groups = [["'-d'", self._dag_path_expr(ref)] for ref in proc.dags]
        if self.kind == 'dag':
            return groups
        for plugin in proc.plugins:
            groups.append(["'--plugin'", self._arg_expr(plugin)])
        groups.append(["'-p'", _py(proc.label)])
        groups.append(["'-s'", _py(proc.setting('sched_name', DEFAULT_SCHED_NAME))])
        if proc.extra_args_note:
            groups.append([_py(a) for a in proc.extra_args_note.split()])
        if proc.setting('cpuprofile'):
            groups.append(["'-c'", "'-o'", self._arg_expr(proc.setting('cpuprofile'))])
        if proc.setting('memprofile'):
            groups.append(["'-H'", "'-O'", self._arg_expr(proc.setting('memprofile'))])
        return groups

    def _composable_nodes(self, proc, indent):
        w = self.w
        w.use('ComposableNode')
        for ref in proc.dags:
            for comment in ref.comments:
                w.comment(comment, indent)
            if self.kind == 'launch':
                w.line('%s# dag_conf: %s' % (indent, ref.text))
            if ref.note:
                w.comment('NOTE: %s' % ref.note, indent)
            if ref.error:
                w.line('%s# WARNING: %s' % (indent, ref.error))
                continue
            for comp in ref.dag.components:
                res = comp.resolution
                w.line('%s# %s { class_name: %s }  %s' % (
                    indent, comp.kind, _escape(comp.class_name), comp.module_library))
                if res.status == 'fallback':
                    w.comment('NOTE: %s' % res.detail, indent)
                elif res.status == 'unresolved':
                    w.comment('WARNING: %s; using the unqualified class name' % res.detail, indent)
                w.line('%sComposableNode(' % indent)
                w.line('%s    package=%s,' % (indent, _py(comp.package)))
                w.line('%s    plugin=%s,' % (indent, _py(comp.plugin)))
                w.line('%s    name=%s,' % (indent, _py(comp.node_name)))
                text = comp.config.to_text()
                lines = text.split('\n')
                # A plain str stays a string parameter (launch_ros only
                # YAML-evaluates substitutions).
                w.line("%s    parameters=[{'component_config': (" % indent)
                for i, line in enumerate(lines):
                    last = i + 1 == len(lines)
                    w.line('%s        %s%s' % (indent, _py(line if last else line + '\n'),
                                               ')}]),' if last else ''))


