class ConversionResult(object):

    def __init__(self, source, kind):
        self.source = source  # label (repository-relative path when possible)
        self.kind = kind  # 'dag' | 'launch'
        self.output = None  # output path (same style as source)
        self.content = None  # None when skipped
        self.skipped = None  # reason when not converted
        self.warnings = []
        self.errors = []
        self.components = 0


def output_path_for(path):
    """P/dag/foo.dag -> P/launch/foo.dag.launch.py, P/launch/bar.launch ->
    P/launch/bar.launch.py; anything else -> <dir>/launch/<name>.py."""
    directory, base = os.path.split(path)
    name = base + ('.launch.py' if base.endswith('.dag') else '.py')
    parent = os.path.basename(directory)
    if parent == 'launch':
        out_dir = directory
    elif parent == 'dag':
        out_dir = os.path.join(os.path.dirname(directory), 'launch')
    else:
        out_dir = os.path.join(directory, 'launch')
    return os.path.join(out_dir, name)


class Converter(object):

    def __init__(self, root=DEFAULT_ROOT):
        self.root = os.path.abspath(root)
        self.resolver = ClassResolver(self.root)
        self._dags = {}
        self._all_dags = None

    # -- paths ----------------------------------------------------------------

    def label(self, path):
        """Repository-relative path when inside the repository, else absolute."""
        path = os.path.abspath(path)
        rel = os.path.relpath(path, self.root)
        if rel == '..' or rel.startswith('..' + os.sep):
            return path
        return rel.replace(os.sep, '/')

    def abspath(self, label):
        return label if os.path.isabs(label) else os.path.join(self.root, label)

    def apollo_relpath(self, dag_conf):
        """Maps a dag_conf entry to a path relative to APOLLO_ROOT (None if it
        is an absolute path outside /apollo)."""
        text = dag_conf.strip()
        if text.startswith('/apollo/'):
            return os.path.normpath(text[len('/apollo/'):]).replace(os.sep, '/')
        if os.path.isabs(text):
            label = self.label(text)
            return None if os.path.isabs(label) else label
        # cyber_launch hands relative paths to mainboard, which resolves them
        # against the Apollo work root.
        return os.path.normpath(text).replace(os.sep, '/')

    # -- dags -----------------------------------------------------------------

    def dag(self, label):
        if label not in self._dags:
            self._dags[label] = load_dag(self.abspath(label), label, self.resolver)
        return self._dags[label]

    def _component_warnings(self, dag, result):
        for comp in dag.components:
            res = comp.resolution
            where = '%s: %s %s' % (dag.path, comp.kind, comp.class_name or '<empty>')
            if res.status == 'unresolved':
                result.errors.append('%s: unresolved class (%s)' % (where, res.detail))
            elif res.status == 'fallback':
                result.warnings.append('%s -> %s (%s)' % (where, res.fq, res.detail))

    def convert_dag(self, path):
        label = self.label(path)
        result = ConversionResult(label, 'dag')
        result.output = output_path_for(label)
        dag = self.dag(label)
        if dag.error:
            result.skipped = 'cannot load dag: %s' % dag.error
            result.errors.append('%s: %s' % (label, result.skipped))
            return result
        self._component_warnings(dag, result)
        stem = os.path.basename(label)[:-len('.dag')]
        proc = Process(stem, 'library')
        relpath = label if not os.path.isabs(label) else None
        proc.dags.append(DagRef(label, relpath, dag, []))
        proc.container_name = self._container_name(stem, [dag])
        self._check_duplicates([proc], result)
        result.components = len(dag.components)
        docs = [
            'Components of the dag, as one rclcpp_components container (default)',
            'or with the Cyber dag runner:',
            '',
            '    ros2 launch apollo %s [runner:=container|mainboard]' % os.path.basename(
                result.output),
            '',
            'runner:=mainboard runs: mainboard -d $APOLLO_ROOT/%s' % (relpath or label),
        ]
        title = 'ROS 2 launch file for the Cyber dag %s.' % label
        result.content = Renderer(label, 'dag', title, docs, [proc]).render()
        return result

    @staticmethod
    def _container_name(label, dags):
        name = to_node_name(label) + '_container'
        taken = {c.node_name for d in dags if d is not None for c in d.components}
        while name in taken:
            name += '_'
        return name

    @staticmethod
    def _check_duplicates(processes, result):
        counts = collections.Counter()
        for proc in processes:
            for ref in proc.dags:
                if ref.dag is not None and not ref.dag.error:
                    counts.update(c.node_name for c in ref.dag.components)
        for name, count in sorted(counts.items()):
            if count > 1:
                result.warnings.append('%s: node name %r is used by %d components'
                                       % (result.source, name, count))

    # -- launch files ---------------------------------------------------------

    def convert_launch(self, path):
        label = self.label(path)
        result = ConversionResult(label, 'launch')
        result.output = output_path_for(label)
        try:
            with open(self.abspath(label), 'rb') as f:
                lf = parse_launch(f.read())
        except (OSError, ET.ParseError) as e:
            result.skipped = 'cannot parse launch file: %s' % e
            result.errors.append('%s: %s' % (label, result.skipped))
            return result
        if lf is None:
            result.skipped = 'not a cyber_launch file (root element is not <cyber>)'
            return result
        processes = self._group(lf, label, result)
        if not processes:
            result.skipped = 'no module could be converted'
            result.errors.append('%s: %s' % (label, result.skipped))
            return result
        self._check_duplicates(processes, result)
        result.components = sum(len(ref.dag.components) for p in processes for ref in p.dags
                                if ref.dag is not None and not ref.dag.error)
        docs = []
        if lf.desc:
            docs.append('desc: %s' % lf.desc)
        if lf.version:
            docs.append('version: %s' % lf.version)
        if docs:
            docs.append('')
        if any(p.kind == 'library' for p in processes):
            docs.append('Each cyber_launch process becomes one rclcpp_components container')
            docs.append('(default) or one Cyber mainboard process:')
            docs.append('')
            docs.append('    ros2 launch apollo %s [runner:=container|mainboard]'
                        % os.path.basename(result.output))
        else:
            docs.append('    ros2 launch apollo %s' % os.path.basename(result.output))
        title = 'ROS 2 launch file for the cyber_launch file %s.' % label
        result.content = Renderer(label, 'launch', title, docs, processes, lf).render()
        return result

    def _group(self, lf, label, result):
        """Groups modules by process_name like cyber_launch: all dags of the
        modules sharing a process_name run in one process."""
        processes = []
        by_name = {}
        for module in lf.modules:
            mtype = module.get('type', 'library') or 'library'
            where = '%s: module %r' % (label, module.name)
            if mtype == 'binary':
                command = module.get('process_name')
                if not command:
                    result.errors.append('%s: binary module without process_name, skipped' % where)
                    continue
                proc = Process(command, 'binary')
                proc.cmd = command.split()
                proc.modules.append(module)
                proc.settings = dict(module.settings)
                processes.append(proc)
                continue
            if mtype != 'library':
                result.warnings.append('%s: unknown type %r, treated as library' % (where, mtype))
            if not module.dags:
                result.errors.append('%s: library module without dag_conf, skipped' % where)
                continue
            name = module.get('process_name') or DEFAULT_PROCESS_NAME
            proc = by_name.get(name)
            if proc is None:
                proc = Process(name, 'library')
                by_name[name] = proc
                processes.append(proc)
            elif proc.modules:
                result.warnings.append('%s: shares process %r with module %r'
                                       % (where, name, proc.modules[0].name))
            proc.modules.append(module)
            self._merge_settings(proc, module, where, result)
            proc.plugins.extend(p for p in module.plugins if p not in proc.plugins)
            for text, comments in module.dags:
                proc.dags.append(self._dag_ref(text, comments, where, result))
        for proc in processes:
            if proc.kind == 'library':
                proc.container_name = self._container_name(
                    proc.label, [r.dag for r in proc.dags])
        return processes

    @staticmethod
    def _merge_settings(proc, module, where, result):
        for key in ('sched_name', 'exception_handler', 'respawn_limit', 'cpuprofile',
                    'memprofile', 'nice'):
            value = module.get(key)
            if not value:
                continue
            if key not in proc.settings:
                proc.settings[key] = value
            elif proc.settings[key] != value:
                note = 'module %r: %s %r ignored, the process uses %r' % (
                    module.name, key, value, proc.settings[key])
                proc.notes.append(note)
                result.warnings.append('%s: conflicting %s for process %r'
                                       % (where, key, proc.label))
        if module.extra_args:
            if proc.extra_args_note is None:
                proc.extra_args_note = module.extra_args
            elif proc.extra_args_note != module.extra_args:
                proc.notes.append('module %r: extra_args %r ignored'
                                  % (module.name, module.extra_args))

    def _dag_ref(self, text, comments, where, result):
        relpath = self.apollo_relpath(text)
        if relpath is None:
            error = 'dag %s is outside /apollo; its components are not inlined' % text
            result.errors.append('%s: %s' % (where, error))
            return DagRef(text, None, None, comments, error)
        note = None
        if not os.path.isfile(os.path.join(self.root, relpath)):
            moved = self._moved_dag(relpath)
            if moved is None:
                error = 'dag file %s not found in the repository' % relpath
                result.errors.append('%s: %s' % (where, error))
                return DagRef(text, relpath, None, comments, error)
            note = '%s does not exist; using %s (the only %s under %s/)' % (
                relpath, moved, os.path.basename(relpath), _module_prefix(relpath))
            result.warnings.append('%s: %s' % (where, note))
            relpath = moved
        dag = self.dag(relpath)
        if dag.error:
            error = 'cannot load dag %s: %s' % (relpath, dag.error)
            result.errors.append('%s: %s' % (where, error))
            return DagRef(text, relpath, dag, comments, error, note)
        self._component_warnings(dag, result)
        return DagRef(text, relpath, dag, comments, None, note)

    def _moved_dag(self, relpath):
        """A dag_conf that does not exist is mapped to the dag with the same
        file name if there is exactly one under the same modules/<module>/."""
        prefix = _module_prefix(relpath)
        if prefix is None:
            return None
        if self._all_dags is None:
            self._all_dags = [self.label(p) for p in self.discover(
                [os.path.join(self.root, d) for d in INDEX_DIRS
                 if os.path.isdir(os.path.join(self.root, d))]) if p.endswith('.dag')]
        name = os.path.basename(relpath)
        found = [d for d in self._all_dags
                 if os.path.basename(d) == name and d.startswith(prefix + '/')]
        return found[0] if len(found) == 1 else None

    # -- entry points ---------------------------------------------------------

    def convert(self, path):
        if path.endswith('.dag'):
            return self.convert_dag(path)
        if path.endswith('.launch'):
            return self.convert_launch(path)
        raise ValueError('not a .dag or .launch file: %s' % path)

    def discover(self, paths=None):
        """Sorted list of absolute paths of the dag/launch files to convert."""
        found = set()
        dirs = []
        for p in paths if paths else [os.path.join(self.root, d) for d in SCAN_DIRS]:
            p = os.path.abspath(p)
            if os.path.isdir(p):
                dirs.append(p)
            elif p.endswith(('.dag', '.launch')) and os.path.isfile(p):
                found.add(p)
            else:
                raise ValueError('not a .dag/.launch file or a directory: %s' % p)
        for d in dirs:
            for dirpath, dirnames, filenames in os.walk(d):
                dirnames[:] = sorted(n for n in dirnames
                                     if not n.startswith(('.', 'bazel-')))
                for name in filenames:
                    if name.endswith(('.dag', '.launch')):
                        found.add(os.path.join(dirpath, name))
        return sorted(found)

    def generated_files(self):
        """Generated launch files currently on disk under SCAN_DIRS."""
        found = []
        for d in SCAN_DIRS:
            for dirpath, dirnames, filenames in os.walk(os.path.join(self.root, d)):
                dirnames[:] = sorted(n for n in dirnames if not n.startswith(('.', 'bazel-')))
                for name in sorted(filenames):
                    if name.endswith('.launch.py'):
                        path = os.path.join(dirpath, name)
                        if _is_generated(path):
                            found.append(path)
        return found


def _module_prefix(relpath):
    """'modules/control/dag/x.dag' -> 'modules/control'."""
    parts = relpath.split('/')
    return '/'.join(parts[:2]) if len(parts) > 2 else None


def _is_generated(path):
    try:
        with open(path, encoding='utf-8', errors='replace') as f:
            return f.readline().startswith(MARKER)
    except OSError:
        return False


def convert_file(path, root=DEFAULT_ROOT):
    """Converts one .dag or .launch file. Returns a ConversionResult whose
    `content` is the Python launch file (None if it was skipped)."""
    return Converter(root).convert(path)


