"""Converts Cyber RT dag files and cyber_launch files into ROS 2 launch files.

    P/dag/foo.dag        ->  P/launch/foo.dag.launch.py
    P/launch/bar.launch  ->  P/launch/bar.launch.py

A source file that is not inside a ``dag/`` or ``launch/`` directory gets a
``launch/`` directory next to it.  Every generated file accepts the launch
argument ``runner:=container|mainboard`` (see docs/ros2/launch.md).

Usage:
    tools/ros2/dag2launch.py               regenerate everything under modules/
    tools/ros2/dag2launch.py --check       exit 1 if a generated file is stale
    tools/ros2/dag2launch.py PATH...       convert only these files/directories
    tools/ros2/dag2launch.py FILE -o OUT   write one conversion to OUT ('-' = stdout)

The output only depends on the input files and the C++ sources used to resolve
class names, so the tool is deterministic and safe to re-run.  It only needs
the Python standard library.
"""

