def _read(path):
    try:
        with open(path, encoding='utf-8') as f:
            return f.read()
    except OSError:
        return None


def main(argv=None):
    parser = argparse.ArgumentParser(
        description='Convert Cyber dag and cyber_launch files into ROS 2 launch files.')
    parser.add_argument('paths', nargs='*',
                        help='.dag/.launch files or directories (default: %s under --root)'
                        % ', '.join(SCAN_DIRS))
    parser.add_argument('--root', default=DEFAULT_ROOT,
                        help='Apollo repository root (default: %(default)s)')
    parser.add_argument('--check', action='store_true',
                        help='do not write; exit 1 if any generated file is missing or stale')
    parser.add_argument('--strict', action='store_true',
                        help='also exit 1 on unresolved classes and broken dag references')
    parser.add_argument('-o', '--output',
                        help="output file for a single input ('-' for stdout)")
    parser.add_argument('-v', '--verbose', action='store_true',
                        help='print notes (fallback class resolutions, shared processes, ...)')
    args = parser.parse_args(argv)

    converter = Converter(args.root)
    try:
        sources = converter.discover(args.paths)
    except ValueError as e:
        parser.error(str(e))
    if args.output and len(sources) != 1:
        parser.error('--output needs exactly one input file')

    results = [converter.convert(path) for path in sources]
    # a dag included by several launch files reports its problems only once
    errors = list(collections.OrderedDict.fromkeys(e for r in results for e in r.errors))
    warnings = list(collections.OrderedDict.fromkeys(w for r in results for w in r.warnings))

    if args.output:
        result = results[0]
        for msg in result.errors:
            print('error: %s' % msg, file=sys.stderr)
        for msg in result.warnings if args.verbose else []:
            print('note: %s' % msg, file=sys.stderr)
        if result.content is None:
            print('error: %s: %s' % (result.source, result.skipped), file=sys.stderr)
            return 1
        if args.output == '-':
            sys.stdout.write(result.content)
        else:
            with open(args.output, 'w', encoding='utf-8') as f:
                f.write(result.content)
        return 1 if args.strict and errors else 0

    outputs = collections.OrderedDict()
    for r in results:
        if r.content is None:
            continue
        out = converter.abspath(r.output)
        if out in outputs:
            print('error: %s and %s both map to %s' % (outputs[out].source, r.source, r.output),
                  file=sys.stderr)
            return 2
        outputs[out] = r

    stale, written = [], []
    for out, r in outputs.items():
        if _read(out) != r.content:
            stale.append(out)
            if not args.check:
                os.makedirs(os.path.dirname(out), exist_ok=True)
                with open(out, 'w', encoding='utf-8') as f:
                    f.write(r.content)
                written.append(out)
    orphans = []
    if not args.paths:
        orphans = [p for p in converter.generated_files() if p not in outputs]
        if not args.check:
            for p in orphans:
                os.remove(p)

    for msg in errors:
        print('error: %s' % msg, file=sys.stderr)
    if args.verbose:
        for msg in warnings:
            print('note: %s' % msg, file=sys.stderr)
    for r in results:
        if r.skipped and not r.errors:
            print('skipped: %s: %s' % (r.source, r.skipped), file=sys.stderr)

    converted = [r for r in results if r.content is not None]
    print('%s: %d dag and %d launch files converted (%d components), %d skipped, '
          '%d errors, %d notes' % (
              TOOL, sum(r.kind == 'dag' for r in converted),
              sum(r.kind == 'launch' for r in converted),
              sum(r.components for r in converted),
              len(results) - len(converted), len(errors), len(warnings)), file=sys.stderr)

    rel = converter.label
    if args.check:
        for p in stale:
            print('stale: %s' % rel(p), file=sys.stderr)
        for p in orphans:
            print('orphan (source removed): %s' % rel(p), file=sys.stderr)
        if stale or orphans:
            print('run %s to regenerate' % TOOL, file=sys.stderr)
            return 1
    else:
        print('%d files written, %d removed, %d unchanged' % (
            len(written), len(orphans), len(outputs) - len(written)), file=sys.stderr)
    return 1 if args.strict and errors else 0


if __name__ == '__main__':
    sys.exit(main())
